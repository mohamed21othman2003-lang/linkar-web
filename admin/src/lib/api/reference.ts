export function specSuggestions(slug: string, spec: string): string[] {
  const c = categories.find((x) => x.slug === slug);
  const used = c ? c.products.flatMap((p) => p.specs.filter(([k]) => k === spec).map(([, v]) => v)) : [];
  return [...new Set([...(productForm(slug).lists[spec] ?? []), ...used].filter((v) => v && v !== "—"))];
}

